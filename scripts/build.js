#!/usr/bin/env node
"use strict";
/* Builds dist/plugin/ (installable layout), the production plugin ZIP and the development project ZIP. No npm dependencies. */
const fs = require("fs"), path = require("path"), { zip } = require("./zip.js");
const ROOT = path.join(__dirname, ".."), DIST = path.join(ROOT, "dist"), STAGE = path.join(DIST, "plugin");
const read = (p) => fs.readFileSync(path.join(ROOT, p));
const text = (p) => read(p).toString("utf8");
function walk(dir, base) { base = base || dir; let out = []; for (const n of fs.readdirSync(dir).sort()) { const f = path.join(dir, n), s = fs.statSync(f); if (s.isDirectory()) out = out.concat(walk(f, base)); else out.push(path.relative(base, f).split(path.sep).join("/")); } return out; }
const uri = (p) => "data:image/png;base64," + read(p).toString("base64");

const manifest = JSON.parse(text("plugin.json"));
const version = manifest.version;
const assetFiles = walk(path.join(ROOT, "assets")).map((f) => "assets/" + f);
manifest.files = assetFiles.concat(["LICENSE"]).sort();
fs.writeFileSync(path.join(ROOT, "plugin.json"), JSON.stringify(manifest, null, 2) + "\n");

/* embed data */
const icons = {}; for (const f of fs.readdirSync(path.join(ROOT, "assets/icons"))) icons[f.replace(/\.svg$/, "")] = text("assets/icons/" + f).trim();
const packs = [];
for (const id of fs.readdirSync(path.join(ROOT, "assets/packs")).sort()) {
  const m = JSON.parse(text("assets/packs/" + id + "/pack.json")), files = {};
  for (const a of m.assets) files[a.path] = uri("assets/packs/" + id + "/" + a.path);
  packs.push({ manifest: m, preview: uri("assets/previews/" + id + ".png"), files });
}
const sampleMeta = JSON.parse(text("assets/samples/sample-slime-sheet.json"));
const prelude = "var CSS_TEXT = " + JSON.stringify(text("src/styles.css")) + ";\nvar ICONS = " + JSON.stringify(icons) + ";\nvar BUNDLED_PACKS = " + JSON.stringify(packs) + ";\nvar BUNDLED_SAMPLE = " + JSON.stringify({ data: uri("assets/samples/sample-slime-sheet.png"), meta: sampleMeta }) + ";\n";
const core = "var Core = (function () { var module = { exports: {} }; (function () {\n" + text("src/core.js") + "\n}).call({}); return module.exports; })();\n";
const bundle = "/* PNG Asset Lab " + version + " - generated by scripts/build.js. Do not edit; edit src/ instead. */\n(function () {\n\"use strict\";\n" + prelude + core + ["support", "packs", "ui", "main"].map((n) => "/* ---- src/" + n + ".js ---- */\n" + text("src/" + n + ".js")).join("\n") + "\n})();\n";

fs.rmSync(DIST, { recursive: true, force: true }); fs.mkdirSync(STAGE, { recursive: true });
const entries = [];
function put(name, data) { const full = path.join(STAGE, name); fs.mkdirSync(path.dirname(full), { recursive: true }); fs.writeFileSync(full, data); entries.push({ name, data: Buffer.isBuffer(data) ? data : Buffer.from(data) }); }
put("plugin.json", JSON.stringify(manifest, null, 2) + "\n"); put("main.js", bundle); put("icon.png", read("icon.png")); put("readme.md", read("readme.md")); put("changelogs.md", read("changelogs.md")); put("LICENSE", read("LICENSE"));
for (const f of assetFiles) put(f, read(f));
entries.sort((a, b) => (a.name === "plugin.json" ? -1 : b.name === "plugin.json" ? 1 : a.name < b.name ? -1 : 1));
const prodName = "png-asset-lab-" + version + "-acode-plugin.zip", devName = "png-asset-lab-" + version + "-dev-project.zip";
fs.writeFileSync(path.join(DIST, prodName), zip(entries));

/* development project archive: sources only, inside one folder, no dist/node_modules/.git/zips */
const skip = /^(dist|node_modules|\.git)(\/|$)|\.zip$/;
const dev = []; (function collect(dir) { for (const n of fs.readdirSync(dir).sort()) { const f = path.join(dir, n), rel = path.relative(ROOT, f).split(path.sep).join("/"); if (skip.test(rel)) continue; if (fs.statSync(f).isDirectory()) collect(f); else dev.push({ name: "png-asset-lab/" + rel, data: fs.readFileSync(f) }); } })(ROOT);
fs.writeFileSync(path.join(DIST, devName), zip(dev));
console.log("built " + prodName + " (" + entries.length + " files) and " + devName + " (" + dev.length + " files); main.js " + (bundle.length / 1024).toFixed(1) + " KB");
